#!/usr/bin/env node
/**
 * Generates the demo fixtures (SVG "pages" + manifest.json) into
 * apps/demo/public/fixtures/. Synthetic art — no licensing concerns.
 *
 *   node scripts/gen-fixtures.mjs
 */
import { mkdir, writeFile, rm } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { strToU8, zipSync } from 'fflate';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outRoot = join(root, 'apps/demo/public/fixtures');

const PALETTES = [
  ['#1e293b', '#38bdf8'],
  ['#3b0764', '#e879f9'],
  ['#052e16', '#4ade80'],
  ['#450a0a', '#fb7185'],
  ['#422006', '#fbbf24'],
  ['#0c4a6e', '#7dd3fc'],
];

function pageSvg({ w, h, label, sub, n }) {
  const [bg, fg] = PALETTES[n % PALETTES.length];
  const panels = [];
  const rows = h > w * 1.6 ? 4 : 2;
  const cols = w > h ? 3 : 2;
  const gap = 24;
  const pw = (w - gap * (cols + 1)) / cols;
  const ph = (h - gap * (rows + 1) - 120) / rows;
  for (let r = 0; r < rows; r++) {
    for (let c = 0; c < cols; c++) {
      const x = gap + c * (pw + gap);
      const y = 100 + gap + r * (ph + gap);
      panels.push(
        `<rect x="${x}" y="${y}" width="${pw}" height="${ph}" rx="10" fill="${fg}" opacity="0.14" stroke="${fg}" stroke-opacity="0.5"/>`,
      );
    }
  }
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${w}" height="${h}" viewBox="0 0 ${w} ${h}">
  <rect width="${w}" height="${h}" fill="${bg}"/>
  ${panels.join('\n  ')}
  <text x="${w / 2}" y="64" fill="${fg}" font-family="system-ui, sans-serif" font-size="40" font-weight="700" text-anchor="middle">${label}</text>
  <text x="${w / 2}" y="${h - 32}" fill="${fg}" font-family="system-ui, sans-serif" font-size="22" text-anchor="middle" opacity="0.8">${sub}</text>
</svg>
`;
}

async function emit(dir, name, contents) {
  const path = join(outRoot, dir, name);
  await mkdir(dirname(path), { recursive: true });
  await writeFile(path, contents);
}

async function manga() {
  const dir = 'demo-manga';
  const W = 840;
  const H = 1200;
  const pages = [];
  let n = 0;
  for (let p = 1; p <= 12; p++) {
    // page 6 is a wide double-page spread
    const wide = p === 6;
    const w = wide ? W * 2 : W;
    const file = `p${String(p).padStart(2, '0')}.svg`;
    await emit(
      dir,
      file,
      pageSvg({
        w,
        h: H,
        label: wide ? `SPREAD ${p}` : `PAGE ${p}`,
        sub: 'demo-manga · RTL · CC0',
        n: n++,
      }),
    );
    pages.push({ src: file, width: w, height: H, ...(wide ? { isWide: true } : {}) });
  }
  await emit(
    dir,
    'manifest.json',
    JSON.stringify(
      {
        type: 'image',
        title: 'Demo Manga (synthetic)',
        direction: 'rtl',
        preferredLayout: 'paged-double',
        pages,
      },
      null,
      2,
    ),
  );
  await emit(dir, 'LICENSE', 'CC0 1.0 — synthetic art generated by scripts/gen-fixtures.mjs\n');
  await emit(
    dir,
    'SOURCE.md',
    '# demo-manga\n\nProcedurally generated placeholder pages. Not a real work.\n',
  );
}

async function webtoon() {
  const dir = 'demo-webtoon';
  const W = 800;
  const H = 2200;
  const pages = [];
  for (let p = 1; p <= 8; p++) {
    const file = `s${String(p).padStart(2, '0')}.svg`;
    await emit(
      dir,
      file,
      pageSvg({ w: W, h: H, label: `STRIP ${p}`, sub: 'demo-webtoon · vertical · CC0', n: p - 1 }),
    );
    pages.push({ src: file, width: W, height: H });
  }
  await emit(
    dir,
    'manifest.json',
    JSON.stringify(
      {
        type: 'image',
        title: 'Demo Webtoon (synthetic)',
        direction: 'vertical',
        preferredLayout: 'continuous-vertical',
        pages,
      },
      null,
      2,
    ),
  );
  await emit(dir, 'LICENSE', 'CC0 1.0 — synthetic art generated by scripts/gen-fixtures.mjs\n');
  await emit(
    dir,
    'SOURCE.md',
    '# demo-webtoon\n\nProcedurally generated placeholder strips. Not a real work.\n',
  );
}

const LOREM =
  'Lorem ipsum dolor sit amet, consectetur adipiscing elit. Sed do eiusmod tempor incididunt ut labore et dolore magna aliqua. Ut enim ad minim veniam, quis nostrud exercitation ullamco laboris nisi ut aliquip ex ea commodo consequat. Duis aute irure dolor in reprehenderit in voluptate velit esse cillum dolore eu fugiat nulla pariatur. Excepteur sint occaecat cupidatat non proident, sunt in culpa qui officia deserunt mollit anim id est laborum. ';

function chapterXhtml(n, title) {
  const paras = Array.from(
    { length: 6 + ((n * 3) % 5) },
    (_, i) => `<p>${LOREM.repeat(2 + (i % 3))}</p>`,
  ).join('\n    ');
  return `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE html>
<html xmlns="http://www.w3.org/1999/xhtml" xmlns:epub="http://www.idpf.org/2007/ops">
  <head><title>${title}</title><link rel="stylesheet" href="style.css"/></head>
  <body>
    <h1 id="top">${title}</h1>
    ${paras}
    <p><a epub:type="noteref" href="notes.xhtml#n${n}">[${n}]</a> a footnote marker.</p>
  </body>
</html>`;
}

async function demoBook() {
  const dir = 'demo-book';
  const chapters = [
    { id: 'c1', file: 'ch1.xhtml', title: 'The Beginning' },
    { id: 'c2', file: 'ch2.xhtml', title: 'A Complication' },
    { id: 'c3', file: 'ch3.xhtml', title: 'The Resolution' },
  ];
  const manifestItems = chapters
    .map((c) => `<item id="${c.id}" href="${c.file}" media-type="application/xhtml+xml"/>`)
    .join('\n    ');
  const spine = chapters.map((c) => `<itemref idref="${c.id}"/>`).join('\n    ');
  const navList = chapters
    .map((c) => `<li><a href="${c.file}">${c.title}</a></li>`)
    .join('\n        ');

  const files = {
    mimetype: strToU8('application/epub+zip'),
    'META-INF/container.xml': strToU8(
      `<?xml version="1.0"?>\n<container xmlns="urn:oasis:names:tc:opendocument:xmlns:container" version="1.0"><rootfiles><rootfile full-path="OEBPS/content.opf" media-type="application/oebps-package+xml"/></rootfiles></container>`,
    ),
    'OEBPS/content.opf': strToU8(
      `<?xml version="1.0" encoding="UTF-8"?>
<package xmlns="http://www.idpf.org/2007/opf" version="3.0" unique-identifier="id">
  <metadata xmlns:dc="http://purl.org/dc/elements/1.1/">
    <dc:identifier id="id">pore-demo-book</dc:identifier>
    <dc:title>The Pore.js Demo Book</dc:title>
    <dc:language>en</dc:language>
    <dc:creator>Synthetic Author</dc:creator>
  </metadata>
  <manifest>
    ${manifestItems}
    <item id="nav" href="nav.xhtml" media-type="application/xhtml+xml" properties="nav"/>
    <item id="notes" href="notes.xhtml" media-type="application/xhtml+xml"/>
    <item id="css" href="style.css" media-type="text/css"/>
  </manifest>
  <spine>
    ${spine}
  </spine>
</package>`,
    ),
    'OEBPS/nav.xhtml': strToU8(
      `<?xml version="1.0" encoding="UTF-8"?>
<html xmlns="http://www.w3.org/1999/xhtml" xmlns:epub="http://www.idpf.org/2007/ops">
  <head><title>Contents</title></head>
  <body><nav epub:type="toc"><h1>Contents</h1><ol>
        ${navList}
      </ol></nav></body>
</html>`,
    ),
    'OEBPS/notes.xhtml': strToU8(
      `<?xml version="1.0" encoding="UTF-8"?>
<html xmlns="http://www.w3.org/1999/xhtml"><head><title>Notes</title></head><body>
  <p id="n1">First note. ${LOREM}</p>
  <p id="n2">Second note. ${LOREM}</p>
  <p id="n3">Third note. ${LOREM}</p>
</body></html>`,
    ),
    'OEBPS/style.css': strToU8(
      `h1 { font-weight: 700; margin: 1.5em 0 0.5em; }\np { margin: 0 0 1em; text-indent: 1.5em; }\np:first-of-type { text-indent: 0; }`,
    ),
  };
  for (const c of chapters) {
    files[`OEBPS/${c.file}`] = strToU8(chapterXhtml(Number(c.id.slice(1)), c.title));
  }

  const epub = zipSync(files, { level: 0 });
  await emit(dir, 'book.epub', epub);
  await emit(
    dir,
    'manifest.json',
    JSON.stringify({ type: 'epub', title: 'The Pore.js Demo Book', file: 'book.epub' }, null, 2),
  );
  await emit(dir, 'LICENSE', 'CC0 1.0 — synthetic text generated by scripts/gen-fixtures.mjs\n');
  await emit(
    dir,
    'SOURCE.md',
    '# demo-book\n\nProcedurally generated placeholder EPUB. Not a real work.\n',
  );
}

await rm(outRoot, { recursive: true, force: true });
await manga();
await webtoon();
await demoBook();
console.log('fixtures written to', outRoot);
