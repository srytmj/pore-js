#!/usr/bin/env node
/**
 * Generates the demo fixtures (SVG "pages" + manifest.json) into
 * apps/demo/public/fixtures/. Synthetic art — no licensing concerns.
 *
 *   node scripts/gen-fixtures.mjs
 */
import { mkdir, writeFile, rm } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outRoot = join(root, 'apps/demo/public/fixtures');

const PALETTES = [
  ['#1e293b', '#38bdf8'],
  ['#3b0764', '#e879f9'],
  ['#052e16', '#4ade80'],
  ['#450a0a', '#fb7185'],
  ['#422006', '#fbbf24'],
  ['#0c4a6e', '#7dd3fc'],
];

function pageSvg({ w, h, label, sub, n }) {
  const [bg, fg] = PALETTES[n % PALETTES.length];
  const panels = [];
  const rows = h > w * 1.6 ? 4 : 2;
  const cols = w > h ? 3 : 2;
  const gap = 24;
  const pw = (w - gap * (cols + 1)) / cols;
  const ph = (h - gap * (rows + 1) - 120) / rows;
  for (let r = 0; r < rows; r++) {
    for (let c = 0; c < cols; c++) {
      const x = gap + c * (pw + gap);
      const y = 100 + gap + r * (ph + gap);
      panels.push(
        `<rect x="${x}" y="${y}" width="${pw}" height="${ph}" rx="10" fill="${fg}" opacity="0.14" stroke="${fg}" stroke-opacity="0.5"/>`,
      );
    }
  }
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${w}" height="${h}" viewBox="0 0 ${w} ${h}">
  <rect width="${w}" height="${h}" fill="${bg}"/>
  ${panels.join('\n  ')}
  <text x="${w / 2}" y="64" fill="${fg}" font-family="system-ui, sans-serif" font-size="40" font-weight="700" text-anchor="middle">${label}</text>
  <text x="${w / 2}" y="${h - 32}" fill="${fg}" font-family="system-ui, sans-serif" font-size="22" text-anchor="middle" opacity="0.8">${sub}</text>
</svg>
`;
}

async function emit(dir, name, contents) {
  const path = join(outRoot, dir, name);
  await mkdir(dirname(path), { recursive: true });
  await writeFile(path, contents);
}

async function manga() {
  const dir = 'demo-manga';
  const W = 840;
  const H = 1200;
  const pages = [];
  let n = 0;
  for (let p = 1; p <= 12; p++) {
    // page 6 is a wide double-page spread
    const wide = p === 6;
    const w = wide ? W * 2 : W;
    const file = `p${String(p).padStart(2, '0')}.svg`;
    await emit(
      dir,
      file,
      pageSvg({
        w,
        h: H,
        label: wide ? `SPREAD ${p}` : `PAGE ${p}`,
        sub: 'demo-manga · RTL · CC0',
        n: n++,
      }),
    );
    pages.push({ src: file, width: w, height: H, ...(wide ? { isWide: true } : {}) });
  }
  await emit(
    dir,
    'manifest.json',
    JSON.stringify(
      {
        type: 'image',
        title: 'Demo Manga (synthetic)',
        direction: 'rtl',
        preferredLayout: 'paged-double',
        pages,
      },
      null,
      2,
    ),
  );
  await emit(dir, 'LICENSE', 'CC0 1.0 — synthetic art generated by scripts/gen-fixtures.mjs\n');
  await emit(
    dir,
    'SOURCE.md',
    '# demo-manga\n\nProcedurally generated placeholder pages. Not a real work.\n',
  );
}

async function webtoon() {
  const dir = 'demo-webtoon';
  const W = 800;
  const H = 2200;
  const pages = [];
  for (let p = 1; p <= 8; p++) {
    const file = `s${String(p).padStart(2, '0')}.svg`;
    await emit(
      dir,
      file,
      pageSvg({ w: W, h: H, label: `STRIP ${p}`, sub: 'demo-webtoon · vertical · CC0', n: p - 1 }),
    );
    pages.push({ src: file, width: W, height: H });
  }
  await emit(
    dir,
    'manifest.json',
    JSON.stringify(
      {
        type: 'image',
        title: 'Demo Webtoon (synthetic)',
        direction: 'vertical',
        preferredLayout: 'continuous-vertical',
        pages,
      },
      null,
      2,
    ),
  );
  await emit(dir, 'LICENSE', 'CC0 1.0 — synthetic art generated by scripts/gen-fixtures.mjs\n');
  await emit(
    dir,
    'SOURCE.md',
    '# demo-webtoon\n\nProcedurally generated placeholder strips. Not a real work.\n',
  );
}

await rm(outRoot, { recursive: true, force: true });
await manga();
await webtoon();
console.log('fixtures written to', outRoot);
